def get_bach_chorales_dict(repo_path: str) -> dict:
    wir_path = os.path.join(
        repo_path,
        "rawdata",
        "When-in-Rome",
        "Corpus",
        "Early_Choral",
        "Bach,_Johann_Sebastian",
        "Chorales",
    )
    chorales_path = os.path.join(
        repo_path, "rawdata", "Chorale-Corpus", "Bach,_Johann_Sebastian", "Chorales"
    )
    result_pairs = {}
    for no in range(1, 372):
        nickname = f"wir-bach-chorales-{no}"
        if nickname in annotation_score_duples:
            result_pairs[nickname] = annotation_score_duples[nickname]
            continue
        folder_name = f"{no:03}"
        rntext_fp = os.path.join(wir_path, folder_name, "analysis.txt")
        score_fp = os.path.join(chorales_path, folder_name, "short_score.mxl")
        rntext_rel = os.path.relpath(rntext_fp, repo_path)
        score_rel = os.path.relpath(score_fp, repo_path)
        result_pairs[nickname] = (rntext_rel, score_rel)
    return result_pairs


